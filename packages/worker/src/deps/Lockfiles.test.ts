/** The versions each lockfile locks a package.json's dependencies at. */
import { expect, test } from "bun:test";
import { nearest, read, relative } from "./Lockfiles";

test("the nearest lockfile pins a package.json, and its workspace path is relative to it", () => {
  const files = new Map([
    ["package-lock.json", ""],
    ["packages/a/package.json", ""],
    ["tools/yarn.lock", ""],
    ["tools/x/package.json", ""],
  ]);

  expect(nearest("packages/a/package.json", files)).toBe("package-lock.json");
  expect(nearest("tools/x/package.json", files)).toBe("tools/yarn.lock");
  expect(relative("packages/a/package.json", "package-lock.json")).toBe(
    "packages/a",
  );
  expect(relative("tools/x/package.json", "tools/yarn.lock")).toBe("x");
  expect(relative("package.json", "package-lock.json")).toBe("");
});

const bunLock = `{
  "lockfileVersion": 1,
  "workspaces": {
    "": { "name": "root", "devDependencies": { "prettier": "^3.0.0", }, },
    "packages/a": { "name": "@x/a", "dependencies": { "effect": "^4.0.0", "semver": "^7.5.0", }, },
  },
  "packages": {
    "@x/a": ["@x/a@workspace:packages/a"],
    "effect": ["effect@4.1.2", "", {}, "sha512-a"],
    "@x/a/effect": ["effect@4.0.6", "", {}, "sha512-b"],
    "prettier": ["prettier@3.9.10", "", {}, "sha512-c"],
    "semver": ["semver@7.6.0", "", {}, "sha512-d"],
  }
}`;

test("bun.lock locks a workspace's own copy over the hoisted one", () => {
  const locked = read("bun.lock", bunLock);

  expect(locked?.("packages/a", "dependencies", "effect", "^4.0.0")).toBe(
    "4.0.6",
  );
  expect(locked?.("packages/a", "dependencies", "semver", "^7.5.0")).toBe(
    "7.6.0",
  );
  expect(locked?.("", "devDependencies", "prettier", "^3.0.0")).toBe("3.9.10");
  expect(locked?.("", "dependencies", "missing", "^1.0.0")).toBeUndefined();
});

const pnpmLock = `lockfileVersion: '9.0'

importers:

  .:
    devDependencies:
      prettier:
        specifier: ^3.0.0
        version: 3.9.10

  packages/a:
    dependencies:
      '@astrojs/check':
        specifier: ^0.9.0
        version: 0.9.4(typescript@5.9.3)

packages:

  prettier@3.9.10:
    resolution: {integrity: sha512-c}
`;

test("pnpm-lock.yaml locks each importer by type, without its peers", () => {
  const locked = read("pnpm-lock.yaml", pnpmLock);

  expect(locked?.("", "devDependencies", "prettier", "^3.0.0")).toBe("3.9.10");
  expect(
    locked?.("packages/a", "dependencies", "@astrojs/check", "^0.9.0"),
  ).toBe("0.9.4");
  expect(
    locked?.("packages/a", "devDependencies", "@astrojs/check", "^0.9.0"),
  ).toBeUndefined();
});

const packageLock = JSON.stringify({
  lockfileVersion: 3,
  packages: {
    "": { name: "root", workspaces: ["packages/*"] },
    "node_modules/a": { resolved: "packages/a", link: true },
    "node_modules/semver": { version: "7.6.0" },
    "packages/a/node_modules/semver": { version: "6.3.1" },
    "node_modules/lru-cache": { version: "6.0.0" },
  },
});

test("package-lock.json locks a workspace's nested copy, then the hoisted one", () => {
  const locked = read("package-lock.json", packageLock);

  expect(locked?.("packages/a", "dependencies", "semver", "^6.0.0")).toBe(
    "6.3.1",
  );
  expect(locked?.("packages/a", "dependencies", "lru-cache", "^6.0.0")).toBe(
    "6.0.0",
  );
  expect(locked?.("", "dependencies", "semver", "^7.5.0")).toBe("7.6.0");
});

const yarnClassic = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@babel/core@^7.0.0", "@babel/core@^7.1.0":
  version "7.26.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.26.0.tgz"

semver@^7.5.0:
  version "7.8.6"
  resolved "https://registry.yarnpkg.com/semver/-/semver-7.8.6.tgz"
`;

const yarnBerry = `__metadata:
  version: 10
  cacheKey: 10c0

"semver@npm:^7.5.0, semver@npm:^7.6.0":
  version: 7.8.6
  resolution: "semver@npm:7.8.6"

"t@workspace:.":
  version: 0.0.0-use.local
  resolution: "t@workspace:."
`;

test("yarn.lock locks each name and range, in Yarn 1 and Berry", () => {
  const classic = read("yarn.lock", yarnClassic);
  const berry = read("yarn.lock", yarnBerry);

  expect(classic?.("", "dependencies", "@babel/core", "^7.1.0")).toBe("7.26.0");
  expect(classic?.("", "dependencies", "semver", "^7.5.0")).toBe("7.8.6");
  expect(berry?.("", "dependencies", "semver", "^7.6.0")).toBe("7.8.6");
  expect(berry?.("", "dependencies", "semver", "^7.4.0")).toBeUndefined();
});
